mus_ovr_b:
    db  $00,$E0,$0D,$38,$10,$1C,$0E,$1C,$0D,$38,$10,$0E,$0E,$0E,$0D,$1C
    db  $09,$1C,$15,$54,$00,$70,$0D,$38,$10,$1C,$0E,$1C,$0D,$1C,$09,$1C,$15,$1C,$14,$1C
    db  $12,$1B,$00,$01,$12,$1C,$10,$38,$15,$1B,$00,$01,$15,$1C,$10,$38
    db  $12,$1B,$00,$01,$12,$1C,$10,$38,$09,$1C,$15,$54
mus_ovr_b_end:

play_ovr:
    ; channel A
    ld  hl, mus_ovr_a
    ld  (ch_a_start), hl
    ld  (ch_a_at), hl
    ld  hl, mus_ovr_a_end-mus_ovr_a
    ld  (ch_a_len), hl
    ld  hl, ch_a_at         ; decrement ch_a_at so when incremented,
    dec (hl)                ; it will start at ch_a_start
    dec (hl)
    ld  a, $01
    ld  (ch_a_ctr), a       ; make it hit 0 at next interrupt

    ; channel B
    ld  hl, mus_ovr_b
    ld  (ch_b_start), hl
    ld  (ch_b_at), hl
    ld  hl, mus_ovr_b_end-mus_ovr_b
    ld  (ch_b_len), hl
    ld  hl, ch_b_at         ; decrement ch_b_at so when incremented,
    dec (hl)                ; it will start at ch_b_start
    dec (hl)
    ld  a, $01
    ld  (ch_b_ctr), a       ; make it hit 0 at next interrupt

    call music_on
    ret
